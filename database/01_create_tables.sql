
-- ==========================================
-- Création des tables de Cinema Booking
-- ==========================================

-- Table des films
CREATE TABLE IF NOT EXISTS films (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titre VARCHAR(255) NOT NULL,
  description TEXT,
  duree INTEGER NOT NULL,
  genre VARCHAR(100),
  actif BOOLEAN DEFAULT TRUE
);

-- Table des salles
CREATE TABLE IF NOT EXISTS salles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(100) UNIQUE NOT NULL,
  capacite INTEGER NOT NULL CHECK (capacite > 0)
);

-- Table des utilisateurs
CREATE TABLE IF NOT EXISTS utilisateurs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(100) NOT NULL,
  prenom VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  mot_de_passe VARCHAR(255) NOT NULL,
  role VARCHAR(30) NOT NULL DEFAULT 'utilisateur',
  date_creation TIMESTAMPTZ DEFAULT NOW()
);

-- Table des séances
CREATE TABLE IF NOT EXISTS seances (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  film_id INTEGER NOT NULL REFERENCES films(id),
  salle_id INTEGER NOT NULL REFERENCES salles(id),
  date_seance DATE NOT NULL,
  heure TIME NOT NULL,
  capacite INTEGER NOT NULL CHECK (capacite > 0),
  statut VARCHAR(30) NOT NULL DEFAULT 'active',
  date_annulation TIMESTAMPTZ
);

-- Table des places
CREATE TABLE IF NOT EXISTS places (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seance_id INTEGER NOT NULL
    REFERENCES seances(id) ON DELETE CASCADE,
  rangee VARCHAR(10) NOT NULL,
  numero INTEGER NOT NULL,
  statut VARCHAR(20) NOT NULL DEFAULT 'disponible',
  UNIQUE (seance_id, rangee, numero)
);

-- Table des réservations
CREATE TABLE IF NOT EXISTS reservations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_reservation VARCHAR(50) UNIQUE NOT NULL,
  seance_id INTEGER NOT NULL REFERENCES seances(id),
  utilisateur_id INTEGER REFERENCES utilisateurs(id)
    ON DELETE RESTRICT,
  nom VARCHAR(100) NOT NULL,
  prenom VARCHAR(100) NOT NULL,
  email VARCHAR(255) NOT NULL,
  telephone VARCHAR(30) NOT NULL,
  date_reservation TIMESTAMPTZ DEFAULT NOW(),
  statut VARCHAR(30) NOT NULL DEFAULT 'confirmee',
  date_annulation TIMESTAMPTZ
);

-- Association entre réservations et places
CREATE TABLE IF NOT EXISTS reservation_places (
  reservation_id INTEGER NOT NULL
    REFERENCES reservations(id) ON DELETE CASCADE,
  place_id INTEGER NOT NULL REFERENCES places(id),
  PRIMARY KEY (reservation_id, place_id)
);

-- Table des billets
CREATE TABLE IF NOT EXISTS billets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_billet VARCHAR(50) UNIQUE NOT NULL,
  reservation_id INTEGER UNIQUE NOT NULL
    REFERENCES reservations(id),
  date_generation TIMESTAMPTZ DEFAULT NOW(),
  statut VARCHAR(30) NOT NULL DEFAULT 'valide',
  date_utilisation TIMESTAMPTZ
);

-- Table des notifications
CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  utilisateur_id INTEGER NOT NULL
    REFERENCES utilisateurs(id),
  message TEXT NOT NULL,
  date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  lu BOOLEAN NOT NULL DEFAULT FALSE
);
